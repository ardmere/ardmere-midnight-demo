/**
 * Emits contract/mst_root_unrolled.compact — pure unrolled 64-leaf,
 * three-asset signed MST root plus unrolled signed/NAV checks.
 *
 * Run: npx tsx scripts/generate-mst-unrolled.compact.ts
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../contract/mst_root_unrolled.compact");

function leafExpr(i: number): string {
  return (
    `Mst_MstNode { hash: Mst_leafHash(userIds[${i}], btcPos[${i}], btcNeg[${i}], ` +
    `ethPos[${i}], ethNeg[${i}], usdtPos[${i}], usdtNeg[${i}]), ` +
    `btcPosSum: btcPos[${i}], btcNegSum: btcNeg[${i}], ` +
    `ethPosSum: ethPos[${i}], ethNegSum: ethNeg[${i}], ` +
    `usdtPosSum: usdtPos[${i}], usdtNegSum: usdtNeg[${i}] }`
  );
}

const decls: string[] = [];
let layer: string[] = Array.from({ length: 64 }, (_, i) => leafExpr(i));

for (let level = 0; layer.length > 1; level++) {
  const next: string[] = [];
  for (let i = 0; i < layer.length; i += 2) {
    const varName = `L${level + 1}_${i >> 1}`;
    decls.push(`    const ${varName} = Mst_parentHash(${layer[i]}, ${layer[i + 1]});`);
    next.push(varName);
  }
  layer = next;
}

const navChecks: string[] = [];
for (let i = 0; i < 64; i++) {
  navChecks.push(
    `    assert(Mst_signedValid(btcPos[${i}], btcNeg[${i}]), "invalid signed btc at ${i}");`,
    `    assert(Mst_signedValid(ethPos[${i}], ethNeg[${i}]), "invalid signed eth at ${i}");`,
    `    assert(Mst_signedValid(usdtPos[${i}], usdtNeg[${i}]), "invalid signed usdt at ${i}");`,
    `    assert(Mst_isPadding(btcPos[${i}], btcNeg[${i}], ethPos[${i}], ethNeg[${i}], usdtPos[${i}], usdtNeg[${i}]) || Mst_navPositive(btcPos[${i}], btcNeg[${i}], ethPos[${i}], ethNeg[${i}], usdtPos[${i}], usdtNeg[${i}], priceBtc, priceEth, priceUsdt), "negative nav at ${i}");`,
  );
}

const source = `// Copyright 2026 Ardmere
// SPDX-License-Identifier: Apache-2.0
// AUTO-GENERATED by scripts/generate-mst-unrolled.compact.ts — do not edit by hand.

pragma language_version 0.23;

module mst_root_unrolled {
  import CompactStandardLibrary;
  import "./mst_hash" prefix Mst_;

  export pure circuit rootFrom64(
    userIds: Vector<64, Bytes<32>>,
    btcPos: Vector<64, Uint<64>>,
    btcNeg: Vector<64, Uint<64>>,
    ethPos: Vector<64, Uint<64>>,
    ethNeg: Vector<64, Uint<64>>,
    usdtPos: Vector<64, Uint<64>>,
    usdtNeg: Vector<64, Uint<64>>
  ): Mst_MstNode {
${decls.join("\n")}
    return ${layer[0]};
  }

  export pure circuit assertNavs(
    btcPos: Vector<64, Uint<64>>,
    btcNeg: Vector<64, Uint<64>>,
    ethPos: Vector<64, Uint<64>>,
    ethNeg: Vector<64, Uint<64>>,
    usdtPos: Vector<64, Uint<64>>,
    usdtNeg: Vector<64, Uint<64>>,
    priceBtc: Uint<64>,
    priceEth: Uint<64>,
    priceUsdt: Uint<64>
  ): [] {
${navChecks.join("\n")}
  }
}
`;

fs.writeFileSync(out, source);
console.log(`Wrote ${out} (${decls.length} combines, ${navChecks.length} checks)`);
